package Looping_Pattern.Basic_Looping;


// 2. Print all even numbers between 1 and 100.


public class Question2 {
    
    public static void main(String[] args) {
        
        for(int i=0; i<=100;i++){
            if (i%2==0) {
                System.out.println(i);
            }
        }

    }

}
